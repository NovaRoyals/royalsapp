function cricketNamed(fullName: string, position: string) {
  const parts = fullName.trim().split(/\s+/);
  const lastName = parts.pop() ?? '';
  const firstName = parts.join(' ');
  return {
    id: `cc-${fullName.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`,
    firstName,
    lastName,
    displayName: `${firstName} ${lastName}`.trim(),
    position,
  };
}

